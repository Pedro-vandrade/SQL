-- ===============================================================================
-- 1. TABELA: a09_cliente
-- ===============================================================================
CREATE TABLE a09_cliente (
    idCliente       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR2(150) NOT NULL,
    email           VARCHAR2(150) NOT NULL,
    telefone        VARCHAR2(10) NOT NULL,
    ddd             CHAR(3) NULL,
    --
    CONSTRAINT pk_a09_cliente PRIMARY KEY (idCliente)
);


CREATE TABLE a09_tipoquarto (
    idTipoQuarto    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nomeTipoQuarto  VARCHAR2(50) NOT NULL,
    --
    CONSTRAINT pk_a09_tipoquarto PRIMARY KEY (idTipoQuarto)
);


CREATE TABLE a09_hotel (
    idHotel         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR2(200) NOT NULL,
    endereco        VARCHAR2(200) NOT NULL,
    estrelas        CHAR(1) NOT NULL,
    --
    CONSTRAINT pk_a09_hotel PRIMARY KEY (idHotel)
);


CREATE TABLE a09_quarto (
    idQuarto        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    numero          CHAR(4) NOT NULL,
    valorDiaria     NUMBER(10,2) NOT NULL,
    idTipoQuarto    NUMBER(10) NOT NULL,
    --
    CONSTRAINT pk_a09_quarto PRIMARY KEY (idQuarto),
    CONSTRAINT fk_quarto_tipoquarto FOREIGN KEY (idTipoQuarto) 
        REFERENCES a09_tipoquarto (idTipoQuarto)
);


CREATE TABLE a09_reserva (
    idReserva       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    dataEntrada     DATE NOT NULL,
    dataSaida       DATE NOT NULL,
    idCliente       NUMBER(10) NOT NULL,
    idHotel         NUMBER(10) NOT NULL,
    --
    CONSTRAINT pk_a09_reserva PRIMARY KEY (idReserva),
    CONSTRAINT fk_reserva_cliente FOREIGN KEY (idCliente) 
        REFERENCES a09_cliente (idCliente),
    CONSTRAINT fk_reserva_hotel FOREIGN KEY (idHotel) 
        REFERENCES a09_hotel (idHotel)
);


CREATE TABLE a09_checkin (
    idCheckin       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    dataEntrada     DATE NOT NULL,
    nroDiarias      NUMBER(10) NOT NULL,
    valorDiaria     NUMBER(10,2) NOT NULL,
    idCliente       NUMBER(10) NOT NULL,
    idHotel         NUMBER(10) NOT NULL,
    idReserva       NUMBER(10) NOT NULL,
    idQuarto        NUMBER(10) NOT NULL,
    --
    CONSTRAINT pk_a09_checkin PRIMARY KEY (idCheckin),
    CONSTRAINT fk_checkin_cliente FOREIGN KEY (idCliente) 
        REFERENCES a09_cliente (idCliente),
    CONSTRAINT fk_checkin_hotel FOREIGN KEY (idHotel) 
        REFERENCES a09_hotel (idHotel),
    CONSTRAINT fk_checkin_reserva FOREIGN KEY (idReserva) 
        REFERENCES a09_reserva (idReserva),
    CONSTRAINT fk_checkin_quarto FOREIGN KEY (idQuarto) 
        REFERENCES a09_quarto (idQuarto)
);